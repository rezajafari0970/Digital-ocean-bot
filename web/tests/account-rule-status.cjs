const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('web/static/app.js','utf8');
const start=source.indexOf('function accountRuleApplicationView(');
const end=source.indexOf('\nfunction ',source.indexOf('function accountRuleSaveMessage(')+1);
const ctx=vm.createContext({esc:x=>String(x).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;'),formatDate:x=>String(x)});
vm.runInContext(source.slice(start,end<0?undefined:end),ctx);
const idle={apply_to_existing:true,shrink_pending:false,replacement_revision:null,waiting_droplet_id:null,retirement_started:false,status:'FUTURE_ONLY',next_action_at:'stale date'};
assert.match(ctx.accountRuleApplicationView(idle).label,/ON · No replacement queued/);
const card=ctx.accountRuleApplicationCard({rule_application:idle});
assert.doesNotMatch(card,/FUTURE ONLY|Next replacement window|stale date/);
assert.match(card,/Turning ON alone/);
for(const p of [null,{}, {apply_to_existing:true}])assert.equal(ctx.accountRuleApplicationView(p).label,'Status unavailable');
const active={...idle,replacement_revision:2,status:'WAITING_SPACING',detail:'Waiting for the next window.'};
assert.match(ctx.accountRuleApplicationCard({rule_application:active}),/WAITING SPACING.*Next replacement window/);
assert.equal(ctx.accountRuleApplicationView({...idle,shrink_pending:true}).pending,true);
const started={...idle,apply_to_existing:false,waiting_droplet_id:'fixture',retirement_started:true};
assert.match(ctx.accountRuleApplicationCard({rule_application:started}),/Deletion already started/);
assert.doesNotMatch(ctx.accountRuleApplicationCard({rule_application:started}),/Next replacement window/);
const unsafe=ctx.accountRuleApplicationCard({rule_application:{...active,status:'<script>',detail:'<img src=x>'}});
assert.doesNotMatch(unsafe,/<script>|<img/);
assert.match(unsafe,/&lt;script&gt;/);
assert.match(ctx.accountRuleSaveMessage({desired_server_count:15,rule_application:idle},{}),/No existing-server replacement is queued.*Desired target: 15/);
assert.match(ctx.accountRuleSaveMessage({desired_server_count:14,rule_application:active},{}),/WAITING SPACING.*Desired target: 14/);
assert.match(ctx.accountRuleSaveMessage(null,{}),/Saved.*status is unavailable/);
assert.match(ctx.accountRuleSaveMessage({rule_application:idle,desired_server_count:15},{token:'not-printed'}),/Token validated/);
assert.match(source,/const refreshed=await refreshAccountsInPlace\(\{force:true\}\);alert\(accountRuleSaveMessage\(refreshed\?cache\.accounts\?\.find/);
assert.match(ctx.accountRuleApplicationView({...active,apply_to_existing:false}).label,/Pending work is stopped/);
assert.match(source,/saved\?'Saved\. Replacement status could not be refreshed/);
console.log('PASS: ON idle, pending, OFF admitted deletion, missing readback, Save feedback and escaping.');

